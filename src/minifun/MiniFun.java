package minifun;

import java.util.*;
import java.util.regex.*;

public class MiniFun {
    //AST NODES (All is an expr <t>)
    interface Node {}
    interface Expr extends Node {}

    // Basic values
    record IntExpr(int value) implements Expr {}
    record BoolExpr(boolean value) implements Expr {} // Uniamo True e False per comodità
    record VarExpr(String name) implements Expr {}

    // Operations
    record BinOpExpr(String op, Expr left, Expr right) implements Expr {}
    record IfExpr(Expr cond, Expr thenBranch, Expr elseBranch) implements Expr {}

    // Scope and functions
    record FunExpr(String param, Expr body) implements Expr {} // fun x => t
    record AppExpr(Expr function, Expr arg) implements Expr {} // t t (es. f 3)
    record LetExpr(String varName, Expr value, Expr body) implements Expr {} // let x = t in t'
    record LetFunExpr(String funName, String param, Expr funBody, Expr body) implements Expr {} // letfun f x = t in t'


    enum TokenType {
        FUN("fun"), IF("if"), THEN("then"), ELSE("else"),
        LETFUN("letfun"), LET("let"), IN("in"), TRUE("true"), FALSE("false"),
        ARROW("=>"), EQCMP("=="), EQASSIGN("="), // <-- Modificati qui!
        PLUS("\\+"), MINUS("-"), MULT("\\*"), LT("<"),
        LPAREN("\\("), RPAREN("\\)"),
        VAR("[a-zA-Z][a-zA-Z0-9]*"), NUM("[0-9]+"), EOF("");

        public final String pattern;
        TokenType(String pattern) { this.pattern = pattern; }
    }

    record Token(TokenType type, String value) {}

    static class Lexer {
        static List<Token> tokenize(String input) {
            List<Token> tokens = new ArrayList<>();
            StringBuilder regex = new StringBuilder();
            for (TokenType t : TokenType.values()) {
                if (t != TokenType.EOF) regex.append(String.format("|(?<%s>%s)", t.name(), t.pattern));
            }
            Matcher m = Pattern.compile(regex.substring(1)).matcher(input);

            while (m.find()) {
                if (m.group().trim().isEmpty()) continue;
                for (TokenType t : TokenType.values()) {
                    if (t != TokenType.EOF && m.group(t.name()) != null) {
                        tokens.add(new Token(t, m.group(t.name())));
                        break;
                    }
                }
            }
            tokens.add(new Token(TokenType.EOF, ""));
            return tokens;
        }
    }

    //Recursive descending parser, generated by AI
    static class Parser {
        private final List<Token> tokens;
        private int pos = 0;

        public Parser(List<Token> tokens) { this.tokens = tokens; }

        private Token current() { return tokens.get(pos); }
        private void advance() { if (pos < tokens.size() - 1) pos++; }

        private boolean match(TokenType expected) {
            if (current().type() == expected) { advance(); return true; }
            return false;
        }

        private void consume(TokenType expected, String errorMsg) {
            if (!match(expected)) throw new RuntimeException(errorMsg + " Trovato: " + current().value());
        }

        // ENTRY POINT: Legge un termine completo <t>
        public Expr parseExpr() {
            // 1. letfun f x = t in t'
            if (match(TokenType.LETFUN)) {
                String funName = current().value();
                consume(TokenType.VAR, "Atteso nome della funzione");
                String param = current().value();
                consume(TokenType.VAR, "Atteso parametro della funzione");
                consume(TokenType.EQASSIGN, "Atteso '='");
                Expr funBody = parseExpr();
                consume(TokenType.IN, "Atteso 'in'");
                Expr mainBody = parseExpr();
                return new LetFunExpr(funName, param, funBody, mainBody);
            }
            // 2. let x = t in t'
            else if (match(TokenType.LET)) {
                String varName = current().value();
                consume(TokenType.VAR, "Atteso nome della variabile");
                consume(TokenType.EQASSIGN, "Atteso '='");
                Expr value = parseExpr();
                consume(TokenType.IN, "Atteso 'in'");
                Expr body = parseExpr();
                return new LetExpr(varName, value, body);
            }
            // 3. fun x => t
            else if (match(TokenType.FUN)) {
                String param = current().value();
                consume(TokenType.VAR, "Atteso parametro per la lambda");
                consume(TokenType.ARROW, "Atteso '=>'");
                Expr body = parseExpr();
                return new FunExpr(param, body);
            }
            // 4. if t then t else t
            else if (match(TokenType.IF)) {
                Expr cond = parseExpr();
                consume(TokenType.THEN, "Atteso 'then'");
                Expr thenBranch = parseExpr();
                consume(TokenType.ELSE, "Atteso 'else'");
                Expr elseBranch = parseExpr();
                return new IfExpr(cond, thenBranch, elseBranch);
            }

            // Se non è nessuna delle parole chiave lunghe, scendiamo negli operatori
            return parseRelOp();
        }

        // Operatori Relazionali: == , <
        private Expr parseRelOp() {
            Expr left = parseAddOp();
            while (current().type() == TokenType.EQCMP || current().type() == TokenType.LT) {
                String op = current().value();
                advance();
                left = new BinOpExpr(op, left, parseAddOp());
            }
            return left;
        }

        // Operatori Additivi: + , -
        private Expr parseAddOp() {
            Expr left = parseMultOp();
            while (current().type() == TokenType.PLUS || current().type() == TokenType.MINUS) {
                String op = current().value();
                advance();
                left = new BinOpExpr(op, left, parseMultOp());
            }
            return left;
        }

        // Operatore Moltiplicativo: *
        private Expr parseMultOp() {
            Expr left = parseApp();
            while (match(TokenType.MULT)) {
                left = new BinOpExpr("*", left, parseApp());
            }
            return left;
        }

        // APPLICAZIONE DI FUNZIONE (La parte più "magica" di minifun.MiniFun)
        // In funzionale f x y significa (f x) y. È associativo a sinistra.
        private Expr parseApp() {
            Expr left = parseAtom();
            // Finché il prossimo token può iniziare un'espressione atomica, stiamo passando argomenti!
            while (isAtomStart()) {
                Expr arg = parseAtom();
                left = new AppExpr(left, arg);
            }
            return left;
        }

        // Un termine atomico è un valore base, una variabile, o un'espressione tra parentesi
        private boolean isAtomStart() {
            TokenType t = current().type();
            return t == TokenType.NUM || t == TokenType.TRUE || t == TokenType.FALSE ||
                    t == TokenType.VAR || t == TokenType.LPAREN;
        }

        private Expr parseAtom() {
            if (current().type() == TokenType.NUM) {
                int val = Integer.parseInt(current().value());
                advance();
                return new IntExpr(val);
            } else if (match(TokenType.TRUE)) {
                return new BoolExpr(true);
            } else if (match(TokenType.FALSE)) {
                return new BoolExpr(false);
            } else if (current().type() == TokenType.VAR) {
                String name = current().value();
                advance();
                return new VarExpr(name);
            } else if (match(TokenType.LPAREN)) {
                Expr expr = parseExpr();
                consume(TokenType.RPAREN, "Attesa chiusura parentesi ')'");
                return expr;
            }
            throw new RuntimeException("Termine imprevisto: " + current().value());
        }
    }
}
