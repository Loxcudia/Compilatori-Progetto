package miniimp;

import java.util.*;
import java.util.regex.*;
public class MiniImp {
    //AST NODES:
    interface Node {}

    // Main Program
    record Prog(String inputVar, String outputVar, Cmd body) implements Node {}

    // Commands
    interface Cmd extends Node {}
    record SkipCmd() implements Cmd {}
    record AssignCmd(String varName, Expr expr) implements Cmd {}
    record SeqCmd(Cmd left, Cmd right) implements Cmd {}
    record IfCmd(BoolExpr cond, Cmd thenBranch, Cmd elseBranch) implements Cmd {}
    record WhileCmd(BoolExpr cond, Cmd body) implements Cmd {}

    // Arithmetic Expr
    interface Expr extends Node {}
    record VarExpr(String name) implements Expr {}
    record IntExpr(int value) implements Expr {}
    record BinOpExpr(String op, Expr left, Expr right) implements Expr {}

    // Boolean expr
    interface BoolExpr extends Node {}
    record TrueBool() implements BoolExpr {}
    record FalseBool() implements BoolExpr {}
    record NotBool(BoolExpr b) implements BoolExpr {}
    record AndBool(BoolExpr left, BoolExpr right) implements BoolExpr {}
    record RelOpBool(Expr left, Expr right) implements BoolExpr {} // For <e> < <e>

    enum TokenType
    {
        DEF("def"), MAIN("main"), WITH("with"), INPUT("input"), OUTPUT("output"), AS("as"),
        SKIP("skip"), IF("if"), THEN("then"), ELSE("else"), WHILE("while"), DO("do"),
        TRUE("true"), FALSE("false"), AND("and"), NOT("not"),
        ASSIGN(":="), SEMI(";"), PLUS("\\+"), MINUS("-"), MULT("\\*"), LT("<"),
        LPAREN("\\("), RPAREN("\\)"),
        VAR("[a-zA-Z][a-zA-Z0-9]*"), NUM("[0-9]+"), EOF("");

        public final String pattern;
        TokenType(String pattern) { this.pattern = pattern; }
    }

    record Token(TokenType type, String value) {}

    static class Lexer
    {
        static List<Token> tokenize(String input)
        {
            List<Token> tokens = new ArrayList<>();
            StringBuilder regex = new StringBuilder();
            for (TokenType t : TokenType.values())
            {
                if (t != TokenType.EOF) regex.append(String.format("|(?<%s>%s)", t.name(), t.pattern));
            }
            Matcher m = Pattern.compile(regex.substring(1)).matcher(input);

            while (m.find())
            {
                if (m.group().trim().isEmpty()) continue;
                for (TokenType t : TokenType.values())
                {
                    if (t != TokenType.EOF && m.group(t.name()) != null)
                    {
                        tokens.add(new Token(t, m.group(t.name())));
                        break;
                    }
                }
            }
            tokens.add(new Token(TokenType.EOF, ""));
            return tokens;
        }
    }

    //Recursive descending parser, generated by AI
    static class Parser {
        private final List<Token> tokens;
        private int pos = 0;

        public Parser(List<Token> tokens) { this.tokens = tokens; }

        private Token current() { return tokens.get(pos); }
        private void advance() { if (pos < tokens.size() - 1) pos++; }

        private boolean match(TokenType expected) {
            if (current().type() == expected) { advance(); return true; }
            return false;
        }

        private void consume(TokenType expected, String errorMsg) {
            if (!match(expected)) throw new RuntimeException(errorMsg + " Trovato: " + current().value());
        }

        // <prog> ::= def main with input <var> output <var> as <cmd>
        public Prog parseProg() {
            consume(TokenType.DEF, "Atteso 'def'");
            consume(TokenType.MAIN, "Atteso 'main'");
            consume(TokenType.WITH, "Atteso 'with'");
            consume(TokenType.INPUT, "Atteso 'input'");

            String inVar = current().value();
            consume(TokenType.VAR, "Atteso nome variabile di input");

            consume(TokenType.OUTPUT, "Atteso 'output'");

            String outVar = current().value();
            consume(TokenType.VAR, "Atteso nome variabile di output");

            consume(TokenType.AS, "Atteso 'as'");

            Cmd body = parseCmd();
            consume(TokenType.EOF, "Attesa fine del file");
            return new Prog(inVar, outVar, body);
        }

        // <cmd> ::= <cmd> ; <cmd>
        public Cmd parseCmd() {
            Cmd cmd = parseSingleCmd();
            while (match(TokenType.SEMI)) {
                Cmd nextCmd = parseSingleCmd();
                cmd = new SeqCmd(cmd, nextCmd);
            }
            return cmd;
        }

        // skip, assign, if, while, (cmd)
        private Cmd parseSingleCmd() {
            if (match(TokenType.SKIP)) {
                return new SkipCmd();
            }
            else if (current().type() == TokenType.VAR) {
                String varName = current().value();
                advance();
                consume(TokenType.ASSIGN, "Atteso ':='");
                return new AssignCmd(varName, parseExpr());
            }
            else if (match(TokenType.IF)) {
                BoolExpr cond = parseBool();
                consume(TokenType.THEN, "Atteso 'then'");
                Cmd thenBranch = parseSingleCmd(); // CORRETTO: valuta solo 1 comando
                consume(TokenType.ELSE, "Atteso 'else'");
                Cmd elseBranch = parseSingleCmd(); // CORRETTO: valuta solo 1 comando
                return new IfCmd(cond, thenBranch, elseBranch);
            }
            else if (match(TokenType.WHILE)) {
                BoolExpr cond = parseBool();
                consume(TokenType.DO, "Atteso 'do'");
                return new WhileCmd(cond, parseSingleCmd()); // CORRETTO: valuta solo 1 comando
            }
            else if (match(TokenType.LPAREN)) {
                // Nota che qui invece DEVE rimanere parseCmd(), perché dentro
                // le parentesi tonde vogliamo poter mettere una sequenza di comandi separati da ';'
                Cmd cmd = parseCmd();
                consume(TokenType.RPAREN, "Attesa ')'");
                return cmd;
            }
            throw new RuntimeException("Comando non valido: " + current().value());
        }

        // <b> ::= <b> and <b> | not <b> | true | false | <e> < <e>
        public BoolExpr parseBool() {
            BoolExpr left = parseBoolTerm();
            while (match(TokenType.AND)) {
                left = new AndBool(left, parseBoolTerm());
            }
            return left;
        }

        private BoolExpr parseBoolTerm() {
            if (match(TokenType.NOT)) {
                return new NotBool(parseBoolTerm());
            } else if (match(TokenType.TRUE)) {
                return new TrueBool();
            } else if (match(TokenType.FALSE)) {
                return new FalseBool();
            } else if (match(TokenType.LPAREN)) {
                // Aggiunto supporto per le parentesi nelle espressioni booleane: ( <b> )
                BoolExpr innerBool = parseBool();
                consume(TokenType.RPAREN, "Attesa ')' dopo l'espressione booleana");
                return innerBool;
            } else {
                // Se non è true/false/not/(, DEVE essere <e> < <e>
                Expr left = parseExpr();
                consume(TokenType.LT, "Atteso '<'");
                Expr right = parseExpr();
                return new RelOpBool(left, right);
            }
        }

        // <e> ::= <e> + <e> | <e> - <e> | <e> * <e> | <var> | <int>
        public Expr parseExpr() {
            Expr left = parseTerm();
            while (current().type() == TokenType.PLUS || current().type() == TokenType.MINUS) {
                String op = current().value();
                advance();
                left = new BinOpExpr(op, left, parseTerm());
            }
            return left;
        }

        private Expr parseTerm() {
            Expr left = parseFactor();
            while (match(TokenType.MULT)) {
                left = new BinOpExpr("*", left, parseFactor());
            }
            return left;
        }

        private Expr parseFactor() {
            if (current().type() == TokenType.NUM) {
                int val = Integer.parseInt(current().value());
                advance();
                return new IntExpr(val);
            } else if (current().type() == TokenType.VAR) {
                String name = current().value();
                advance();
                return new VarExpr(name);
            } else if (match(TokenType.LPAREN)) {
                // Aggiunto supporto per le parentesi nelle espressioni matematiche: ( <e> )
                Expr innerExpr = parseExpr();
                consume(TokenType.RPAREN, "Attesa ')' dopo l'espressione matematica");
                return innerExpr;
            }
            throw new RuntimeException("Espressione non valida: " + current().value());
        }
}}
